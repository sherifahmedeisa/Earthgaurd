async function seedVolunteers() {
  console.log(`[v0] Starting to seed ${volunteers.length} volunteers...`)

  let successCount = 0
  let errorCount = 0
  const hallNumbers = ["A", "B", "C", "D", "E", "F", "G", "H"]

  for (let i = 0; i < volunteers.length; i++) {
    const volunteer = volunteers[i]
    const hallIndex = i % hallNumbers.length
    const hall = hallNumbers[hallIndex]
    const volunteerType = Number.parseInt(volunteer.code) % 2 === 1 ? "ceta" : "delta"

    try {
      await sql.query(
        "INSERT INTO volunteers (name, email, hall_number, volunteer_type, details) VALUES ($1, $2, $3, $4, $5) ON CONFLICT (email) DO NOTHING",
        [volunteer.name, volunteer.email, hall, volunteerType, { volunteer_id: volunteer.code }],
      )
      successCount++
      console.log(`[v0] Added volunteer ${successCount}/${volunteers.length}: ${volunteer.name}`)
    } catch (error) {
      errorCount++
      console.error(`[v0] Error adding volunteer ${volunteer.name}:`, error)
    }
  }

  console.log(`[v0] Seeding complete! Successfully added: ${successCount}, Errors: ${errorCount}`)
}

